#!/usr/bin/env python3
"""Generates expected HMAC/HKDF/PBKDF2 values over SHA3-256 with the OpenSSL CLI.

There are no official vectors for these constructions with SHA-3, so OpenSSL is the
reference (AGENTS.md, section 9). Inputs are deterministic byte patterns; outputs come
only from OpenSSL. Usage: python3 -I generate.py  (writes *.rsp next to this script)
"""

import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))


def pattern(n, seed):
    return bytes((seed + 7 * i) & 0xFF for i in range(n))


def hexs(b):
    return b.hex()


def openssl(args, stdin=b""):
    out = subprocess.run(["openssl", *args], input=stdin, capture_output=True, check=True)
    return bytes.fromhex(out.stdout.decode().strip().replace(":", ""))


def hmac(key, msg):
    return openssl(["mac", "-digest", "SHA3-256", "-macopt", "hexkey:" + hexs(key), "HMAC"], msg)


def hkdf(ikm, salt, info, length, mode=None):
    args = ["kdf", "-keylen", str(length), "-kdfopt", "digest:SHA3-256",
            "-kdfopt", "hexkey:" + hexs(ikm), "-kdfopt", "hexsalt:" + hexs(salt),
            "-kdfopt", "hexinfo:" + hexs(info)]
    if mode:
        args += ["-kdfopt", "mode:" + mode]
    return openssl(args + ["HKDF"])


def pbkdf2(password, salt, iterations, length):
    return openssl(["kdf", "-keylen", str(length), "-kdfopt", "digest:SHA3-256",
                    "-kdfopt", "hexpass:" + hexs(password), "-kdfopt", "hexsalt:" + hexs(salt),
                    "-kdfopt", "iter:" + str(iterations), "PBKDF2"])


def header(f, what):
    version = subprocess.run(["openssl", "version"], capture_output=True, check=True)
    f.write(f"# {what} over SHA3-256, generated by tests/kat/kdf/generate.py\n")
    f.write(f"# {version.stdout.decode().strip()}\n\n")


def main():
    # SHA3-256 block size (rate) is 136 bytes: cover keys shorter, equal and longer.
    with open(os.path.join(HERE, "hmac_sha3_256.rsp"), "w") as f:
        header(f, "HMAC")
        count = 0
        for klen in (0, 1, 20, 32, 135, 136, 137, 200):
            for mlen in (0, 1, 50, 135, 136, 137, 1000):
                key, msg = pattern(klen, 0x0B + klen), pattern(mlen, 0x31 + mlen)
                f.write(f"COUNT = {count}\nKey = {hexs(key)}\nMsg = {hexs(msg)}\n"
                        f"Mac = {hexs(hmac(key, msg))}\n\n")
                count += 1

    with open(os.path.join(HERE, "hkdf_sha3_256.rsp"), "w") as f:
        header(f, "HKDF (RFC 5869)")
        cases = [(22, 13, 10, 42), (80, 80, 80, 82), (22, 0, 0, 42), (32, 32, 0, 32),
                 (32, 64, 17, 1), (64, 136, 40, 100), (16, 200, 5, 255 * 32)]
        for count, (ilen, slen, nlen, length) in enumerate(cases):
            ikm, salt, info = pattern(ilen, 0x0B), pattern(slen, 0x00), pattern(nlen, 0xF0)
            prk = hkdf(ikm, salt, info, 32, "EXTRACT_ONLY")
            okm = hkdf(ikm, salt, info, length)
            f.write(f"COUNT = {count}\nIKM = {hexs(ikm)}\nSalt = {hexs(salt)}\n"
                    f"Info = {hexs(info)}\nL = {length}\nPRK = {hexs(prk)}\nOKM = {hexs(okm)}\n\n")

    with open(os.path.join(HERE, "pbkdf2_hmac_sha3_256.rsp"), "w") as f:
        header(f, "PBKDF2-HMAC (RFC 8018)")
        cases = [(b"password", b"salt", 1, 32), (b"password", b"salt", 2, 32),
                 (b"password", b"salt", 4096, 32), (b"", pattern(16, 1), 3, 32),
                 (b"passwordPASSWORDpassword", b"saltSALTsaltSALTsaltSALTsaltSALTsalt", 4096, 40),
                 (pattern(200, 9), pattern(16, 2), 10, 64), (b"pass\0word", b"sa\0lt", 4096, 16),
                 (b"correct horse battery staple", pattern(16, 3), 20000, 32)]
        for count, (pw, salt, it, length) in enumerate(cases):
            f.write(f"COUNT = {count}\nPassword = {hexs(pw)}\nSalt = {hexs(salt)}\n"
                    f"Iterations = {it}\nDKLen = {length}\n"
                    f"DK = {hexs(pbkdf2(pw, salt, it, length))}\n\n")


if __name__ == "__main__":
    main()
